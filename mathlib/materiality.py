# -*- coding: utf-8 -*-
"""mathlib/materiality.py — существенность эффекта для компании (решение владельца 07.11).

Вопрос продукта: $50 млн дополнительной прибыли — шум для гиганта и всё для маленькой компании.
Идея проходит, только если эффект СУЩЕСТВЕН относительно размера бизнеса и держится достаточно долго.

Детерминированно (Инв#6), все входы и пороги — в результате (П8). Пороги — допущения по умолчанию,
переопределяются вызывающим (config) и показываются владельцу вместе с вердиктом.
"""

DEFAULT_THRESHOLDS = {
    "доля_прибыли_существенно": 0.10,     # ≥10% годовой чистой прибыли — существенно
    "доля_прибыли_пограничный": 0.03,     # 3–10% — пограничный
    "доля_выручки_существенно": 0.05,     # для убыточных: ≥5% выручки
    "доля_выручки_пограничный": 0.015,
    "доля_капитализации_существенно": 0.10,   # приведённый эффект ≥10% капитализации
    "доля_капитализации_пограничный": 0.03,
}
СУЩЕСТВЕННО, ПОГРАНИЧНЫЙ, ШУМ = "СУЩЕСТВЕННО", "ПОГРАНИЧНЫЙ", "ШУМ"


def _ratio(a, b):
    return round(a / b, 4) if a is not None and b not in (None, 0) and b > 0 else None


def _grade(v, hi, lo):
    if v is None:
        return None
    return СУЩЕСТВЕННО if v >= hi else (ПОГРАНИЧНЫЙ if v >= lo else ШУМ)


def effect_value(effect_profit_per_year, years, r=0.09):
    """Приведённая стоимость эффекта: годовая доп. прибыль × аннуитет на `years` лет при ставке r."""
    if effect_profit_per_year is None or years is None or years <= 0:
        return None
    annuity = (1 - (1 + r) ** (-years)) / r
    return round(effect_profit_per_year * annuity, 2)


def materiality(effect_profit_per_year=None, effect_revenue_per_year=None, years=None, net_income=None,
                revenue=None, market_cap=None, r=0.09, thresholds=None):
    """Эффект относительно компании. Все суммы — в одной валюте и одном масштабе (например, млн $ в год).

    Вердикт — по самому информативному доступному мерилу: доля капитализации (если известны срок и
    капитализация) → доля прибыли (если прибыль > 0) → доля выручки. Нечем мерить — честный отказ."""
    th = dict(DEFAULT_THRESHOLDS, **(thresholds or {}))
    pv = effect_value(effect_profit_per_year, years, r)
    m = {
        "доля_прибыли": _ratio(effect_profit_per_year, net_income) if (net_income or 0) > 0 else None,
        "доля_выручки": _ratio(effect_revenue_per_year, revenue),
        "доля_капитализации": _ratio(pv, market_cap),
    }
    grades = {
        "доля_капитализации": _grade(m["доля_капитализации"], th["доля_капитализации_существенно"],
                                     th["доля_капитализации_пограничный"]),
        "доля_прибыли": _grade(m["доля_прибыли"], th["доля_прибыли_существенно"], th["доля_прибыли_пограничный"]),
        "доля_выручки": _grade(m["доля_выручки"], th["доля_выручки_существенно"], th["доля_выручки_пограничный"]),
    }
    basis = next((k for k in ("доля_капитализации", "доля_прибыли", "доля_выручки") if grades[k]), None)
    out = {"входы": {"эффект_прибыль_в_год": effect_profit_per_year, "эффект_выручка_в_год": effect_revenue_per_year,
                     "лет": years, "чистая_прибыль": net_income, "выручка": revenue, "капитализация": market_cap,
                     "r": r},
           "пороги": th, "приведённый_эффект": pv, "мерила": m, "оценки": grades}
    if basis is None:
        out.update(ok=False, вердикт=None,
                   причина="нечем мерить: нужен эффект и хотя бы одно из — прибыль > 0, выручка, капитализация со сроком")
        return out
    out.update(ok=True, вердикт=grades[basis], основание=basis)
    if years is not None and years < 1:
        out["оговорка"] = "эффект короче года — даже большой разовый эффект редко меняет стоимость компании"
    return out
