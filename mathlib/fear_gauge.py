# -*- coding: utf-8 -*-
"""mathlib/fear_gauge.py — датчик «цена защиты»: страх на рынке сейчас дорогой или дешёвый (Q-цена-страха, 22.11). Инв#6.

Владелец 22.11 хочет зарабатывать на турбулентности. Защита от падения (опцион «пут») и ставки на падение через
опционы стоят тем дороже, чем большие колебания рынок закладывает в цены опционов. Покупать их разумно, когда страх
дёшев, а не после всплеска. Датчик сравнивает три числа (все — годовые колебания, доля: 0.26 = 26%):
  • закладывают — колебания, которые опционы на широкий рынок закладывают на ближайший месяц (приходит снаружи);
  • за_месяц    — фактические колебания рынка за последние 21 торговый день;
  • обычные     — фактические колебания за последние ~3 года (756 торговых дней).
Фактические колебания — стандартное отклонение дневных логарифмических доходностей × √252.

ВЕРДИКТ ставится по УРОВНЮ: во сколько раз закладываемые колебания выше обычных.
  «дорогая»  — в EXPENSIVE_VS_USUAL (1.5) раза и больше;
  «дешёвая»  — не больше обычных (CHEAP_VS_USUAL = 1.0);
  «обычная»  — между ними.
Сравнение с недавними фактическими вердикт НЕ меняет, а объясняет его: опционы закладывают больше, чем рынок реально
колеблется (наценка за страх), или рынок и правда так трясёт (цена уже случившегося всплеска). Так сделано намеренно:
посреди обвала фактические колебания бывают выше закладываемых, но защита при этом всё равно стоит кратно дороже
обычного — датчик не должен в этот момент говорить «обычная».

Честно о порогах (П8): это ориентиры-константы, а не калибровка на нашей истории. Опционы почти всегда закладывают
чуть больше, чем рынок потом показывает, поэтому «не больше обычных» — уже заметно дёшево. Когда в датированных
снимках reports/sectors/ накопится своя история датчика, пороги стоит проверить по ней.

Нет закладываемых колебаний (нет данных об опционах) → вердикт None («не измерено»); фактические всё равно
возвращаются. Мало истории цен → соответствующее число None, без выдумок.
"""
import math

TRADING_DAYS = 252            # торговых дней в году — перевод дневных колебаний в годовые
RECENT_DAYS = 21              # «за месяц»
USUAL_DAYS = 756              # «обычные»: ~3 года
USUAL_MIN_DAYS = 504          # меньше двух лет истории — «обычные» не считаем (иначе «обычным» станет один режим рынка)
EXPENSIVE_VS_USUAL = 1.5      # закладывают в полтора раза больше обычных и выше → «дорогая»
CHEAP_VS_USUAL = 1.0          # закладывают не больше обычных → «дешёвая»
PREMIUM_VS_RECENT = 1.1       # закладывают на 10%+ больше недавних фактических → в объяснении «наценка за страх»
IMPLIED_MIN, IMPLIED_MAX = 0.03, 2.0      # вне этих границ число от поставщика — мусор, а не измерение

EXPENSIVE, NORMAL, CHEAP = "дорогая", "обычная", "дешёвая"


def _num(x):
    try:
        v = float(x)
        return v if math.isfinite(v) else None
    except (TypeError, ValueError):
        return None


def _vals(closes):
    """[(дата, цена)] или [цена] → список положительных цен по порядку."""
    out = []
    for c in closes or []:
        v = _num(c[1] if isinstance(c, (list, tuple)) else c)
        if v is not None and v > 0:
            out.append(v)
    return out


def realized_vol(closes, days):
    """Годовые фактические колебания по последним `days` дневным доходностям. Доходностей меньше `days` → None."""
    v = _vals(closes)
    days = int(days)
    if days < 2 or len(v) < days + 1:
        return None
    w = v[-(days + 1):]
    r = [math.log(w[i] / w[i - 1]) for i in range(1, len(w))]
    mean = sum(r) / len(r)
    var = sum((x - mean) ** 2 for x in r) / (len(r) - 1)
    return math.sqrt(var) * math.sqrt(TRADING_DAYS)


def measures(closes):
    """→ {'за_месяц', 'обычные', 'дней_обычных', 'дата'}: фактические колебания (None, если истории мало).
    «Обычные» считаются по последним USUAL_DAYS доходностям, а если истории меньше — по всей, но не короче
    USUAL_MIN_DAYS (число дней пишется рядом, чтобы «3 года» не подменялись молча)."""
    v = _vals(closes)
    n = min(len(v) - 1, USUAL_DAYS)
    recent = realized_vol(v, RECENT_DAYS)
    usual = realized_vol(v, n) if n >= USUAL_MIN_DAYS else None
    last = (closes or [None])[-1]
    return {"за_месяц": None if recent is None else round(recent, 4),
            "обычные": None if usual is None else round(usual, 4),
            "дней_обычных": n if usual is not None else None,
            "дата": str(last[0])[:10] if isinstance(last, (list, tuple)) and last and last[0] else None}


def _pct(x):
    return f"{round(x * 100)}%"


def verdict(implied, usual, recent=None):
    """Закладываемые, обычные и недавние фактические колебания (доли) → (вердикт | None, [объяснение словами]).
    Вердикт — по отношению к обычным; недавние только объясняют (см. шапку модуля)."""
    iv, us, rc = _num(implied), _num(usual), _num(recent)
    if iv is None or not (IMPLIED_MIN <= iv <= IMPLIED_MAX):
        return None, ["нет данных о том, какие колебания закладывают опционы, — цена защиты не измерена"]
    if us is None or us <= 0:
        return None, ["мало истории цен, чтобы посчитать обычные колебания рынка, — цена защиты не измерена"]
    k = round(iv / us, 6)             # округление: 0.24 / 0.16 — это ровно порог 1.5, а не 1.4999999999999998
    if k >= EXPENSIVE_VS_USUAL:
        v = EXPENSIVE
        why = [f"опционы закладывают колебания в {k:.1f} раза больше обычных ({_pct(iv)} против {_pct(us)}); "
               f"порог «дорогой» — в {EXPENSIVE_VS_USUAL:g} раза"]
    elif k <= CHEAP_VS_USUAL:
        v = CHEAP
        why = [f"опционы закладывают колебания не больше обычных ({_pct(iv)} против {_pct(us)}), хотя обычно "
               "закладывают с запасом"]
    else:
        v = NORMAL
        why = [f"опционы закладывают колебания в {k:.1f} раза больше обычных ({_pct(iv)} против {_pct(us)}) — в привычных "
               f"пределах (дёшево — не больше обычных, дорого — в {EXPENSIVE_VS_USUAL:g} раза)"]
    if rc is not None and rc > 0:
        if iv >= rc * PREMIUM_VS_RECENT:
            why.append(f"это больше, чем рынок реально колебался за последний месяц ({_pct(rc)}), — в цене есть наценка "
                       "за страх")
        elif iv < rc:
            why.append(f"за последний месяц рынок реально колебался сильнее ({_pct(rc)}), чем закладывают опционы, — "
                       "это цена уже случившейся встряски")
        else:
            why.append(f"это примерно столько, сколько рынок реально колебался за последний месяц ({_pct(rc)})")
    return v, why


def gauge(closes, implied=None):
    """Главная функция. closes — [(дата, цена)] по возрастанию даты; implied — закладываемые опционами годовые
    колебания (доля) или None. → {'закладывают', 'за_месяц', 'обычные', 'дней_обычных', 'дата', 'к_обычным',
    'к_недавним', 'вердикт': 'дорогая'|'обычная'|'дешёвая'|None, 'почему': [...], 'пороги': {...}}."""
    ms = measures(closes)
    iv = _num(implied)
    if iv is not None and not (IMPLIED_MIN <= iv <= IMPLIED_MAX):
        iv = None
    v, why = verdict(iv, ms["обычные"], ms["за_месяц"])
    return {**ms, "закладывают": None if iv is None else round(iv, 4),
            "к_обычным": round(iv / ms["обычные"], 2) if iv is not None and ms["обычные"] else None,
            "к_недавним": round(iv / ms["за_месяц"], 2) if iv is not None and ms["за_месяц"] else None,
            "вердикт": v, "почему": why,
            "пороги": {"дорогая_от": EXPENSIVE_VS_USUAL, "дешёвая_до": CHEAP_VS_USUAL}}


TAILS = {
    EXPENSIVE: "защиту от падения (опцион «пут») и ставки на падение лучше покупать, когда она дешёвая, а не после "
               "всплеска страха",
    NORMAL: "сама цена защиты сейчас не довод ни за, ни против идей на падение",
    CHEAP: "страх дёшев — защиту от падения (опцион «пут») и идеи на падение выгоднее рассматривать сейчас, чем после "
           "всплеска",
}


def phrase(g, market="S&P 500 (фонд SPY)"):
    """Одна фраза простыми словами из результата gauge (или из снимка). Вердикта нет → None (фразы нет)."""
    if not isinstance(g, dict) or g.get("вердикт") not in TAILS:
        return None
    iv, us, rc = _num(g.get("закладывают")), _num(g.get("обычные")), _num(g.get("за_месяц"))
    if iv is None or us is None:
        return None
    exp = (g.get("опционы") or {}).get("экспирация") if isinstance(g.get("опционы"), dict) else None
    s = (f"Цена защиты: {g['вердикт']} — опционы на {market} закладывают {_pct(iv)} годовых колебаний"
         + (f" (на срок до {exp})" if exp else "") + " при ")
    if rc is not None:
        s += f"фактических {_pct(rc)} за месяц и "
    s += f"обычных {_pct(us)}; {TAILS[g['вердикт']]}."
    return s


def phrase_unmeasured(g, market="S&P 500 (фонд SPY)"):
    """Честная строка для карты, когда вердикта нет: что не измерено и что всё-таки известно."""
    if not isinstance(g, dict) or g.get("вердикт") in TAILS:
        return None
    reason = g.get("не_измерено") or "; ".join(g.get("почему") or []) or "нет данных"
    s = f"Цена защиты: не измерена — {reason}."
    rc, us = _num(g.get("за_месяц")), _num(g.get("обычные"))
    known = [x for x in ((f"{_pct(rc)} за месяц" if rc is not None else None),
                         (f"обычно {_pct(us)}" if us is not None else None)) if x]
    if known:
        s += f" Фактические годовые колебания {market}: " + ", ".join(known) + "."
    return s
